package cdngen

import (
	"fmt"
	"strings"
)

// ConfigOptions defines the caching behavior to export.
type ConfigOptions struct {
	BackendHost        string   `json:"backendHost"`
	PathPrefix         string   `json:"pathPrefix"`
	EdgeTTLSeconds     int      `json:"edgeTtlSeconds"`
	BrowserTTLSeconds  int      `json:"browserTtlSeconds"`
	EnableSWR          bool     `json:"enableSwr"`
	SWRDurationSeconds int      `json:"swrDurationSeconds"`
	EnableSIE          bool     `json:"enableSie"`
	SIEDurationSeconds int      `json:"sieDurationSeconds"`
	SurrogateKeys      []string `json:"surrogateKeys"`
	StripCookies       bool     `json:"stripCookies"`
	StripMarketingQP   bool     `json:"stripMarketingQp"`
}

// DefaultOptions provides sensible production defaults.
func DefaultOptions() ConfigOptions {
	return ConfigOptions{
		BackendHost:        "origin.example.com",
		PathPrefix:         "/",
		EdgeTTLSeconds:     3600,
		BrowserTTLSeconds:  300,
		EnableSWR:          true,
		SWRDurationSeconds: 86400,
		EnableSIE:          true,
		SIEDurationSeconds: 86400,
		SurrogateKeys:      []string{"catalog", "products"},
		StripCookies:       true,
		StripMarketingQP:   true,
	}
}

// GeneratedConfigs contains ready-to-deploy configuration files for the top CDN & proxy platforms.
type GeneratedConfigs struct {
	NginxConf           string `json:"nginxConf"`
	FastlyVCL           string `json:"fastlyVcl"`
	CloudflareTerraform string `json:"cloudflareTerraform"`
	CloudFrontTerraform string `json:"cloudFrontTerraform"`
}

// GenerateAll produces snippets across Nginx, Fastly VCL, Cloudflare Terraform, and CloudFront.
func GenerateAll(opts ConfigOptions) GeneratedConfigs {
	if opts.BackendHost == "" {
		opts.BackendHost = "origin.example.com"
	}
	if opts.PathPrefix == "" {
		opts.PathPrefix = "/"
	}
	if opts.EdgeTTLSeconds <= 0 {
		opts.EdgeTTLSeconds = 3600
	}
	if opts.BrowserTTLSeconds <= 0 {
		opts.BrowserTTLSeconds = 300
	}
	if opts.SWRDurationSeconds <= 0 {
		opts.SWRDurationSeconds = 86400
	}
	if opts.SIEDurationSeconds <= 0 {
		opts.SIEDurationSeconds = 86400
	}

	return GeneratedConfigs{
		NginxConf:           generateNginx(opts),
		FastlyVCL:           generateFastly(opts),
		CloudflareTerraform: generateCloudflare(opts),
		CloudFrontTerraform: generateCloudFront(opts),
	}
}

func generateNginx(opts ConfigOptions) string {
	var b strings.Builder
	b.WriteString("# Nginx Reverse Proxy & RFC 9111 HTTP Cache Configuration\n")
	b.WriteString("# Generated by EdgeLens\n\n")
	b.WriteString("proxy_cache_path /var/cache/nginx/edge levels=1:2 keys_zone=edgelens_zone:20m\n")
	b.WriteString("                 max_size=2g inactive=120m use_temp_path=off;\n\n")

	b.WriteString("server {\n")
	b.WriteString("    listen 80;\n")
	b.WriteString("    server_name edge.example.com;\n\n")

	b.WriteString(fmt.Sprintf("    location %s {\n", opts.PathPrefix))
	b.WriteString(fmt.Sprintf("        proxy_pass http://%s;\n", opts.BackendHost))
	b.WriteString("        proxy_cache edgelens_zone;\n")
	b.WriteString("        proxy_cache_key \"$scheme$request_method$host$uri$is_args$args\";\n")
	b.WriteString(fmt.Sprintf("        proxy_cache_valid 200 301 302 %ds;\n", opts.EdgeTTLSeconds))

	if opts.EnableSWR || opts.EnableSIE {
		var stales []string
		stales = append(stales, "error", "timeout", "invalid_header", "updating")
		if opts.EnableSIE {
			stales = append(stales, "http_500", "http_502", "http_503", "http_504")
		}
		b.WriteString(fmt.Sprintf("        proxy_cache_use_stale %s;\n", strings.Join(stales, " ")))
	}

	if opts.EnableSWR {
		b.WriteString("        proxy_cache_background_update on;\n")
		b.WriteString("        proxy_cache_lock on;\n")
	}

	if opts.StripCookies {
		b.WriteString("        proxy_ignore_headers Set-Cookie;\n")
		b.WriteString("        proxy_hide_header Set-Cookie;\n")
	}

	b.WriteString("        proxy_hide_header Surrogate-Control;\n")
	b.WriteString("        proxy_hide_header Surrogate-Key;\n")
	b.WriteString("        add_header X-Cache-Status $upstream_cache_status;\n")
	b.WriteString("    }\n")
	b.WriteString("}\n")
	return b.String()
}

func generateFastly(opts ConfigOptions) string {
	var b strings.Builder
	b.WriteString("# Fastly VCL Caching Snippet\n")
	b.WriteString("# Generated by EdgeLens\n\n")

	b.WriteString("sub vcl_recv {\n")
	b.WriteString("  # FASTLY recv\n")
	if opts.StripMarketingQP {
		b.WriteString("  # Strip marketing query parameters to consolidate cache hits\n")
		b.WriteString("  if (req.url ~ \"[?&](utm_[a-z]+|fbclid|gclid)=\") {\n")
		b.WriteString("    set req.url = querystring.regfilter(req.url, \"^(utm_[a-z]+|fbclid|gclid)$\");\n")
		b.WriteString("  }\n")
	}
	b.WriteString("}\n\n")

	b.WriteString("sub vcl_backend_response {\n")
	b.WriteString("  # FASTLY fetch\n")
	b.WriteString(fmt.Sprintf("  # Set edge TTL to %d seconds\n", opts.EdgeTTLSeconds))
	b.WriteString(fmt.Sprintf("  set beresp.ttl = %ds;\n", opts.EdgeTTLSeconds))

	if opts.EnableSWR {
		b.WriteString(fmt.Sprintf("  set beresp.stale_while_revalidate = %ds;\n", opts.SWRDurationSeconds))
	}
	if opts.EnableSIE {
		b.WriteString(fmt.Sprintf("  set beresp.stale_if_error = %ds;\n", opts.SIEDurationSeconds))
	}

	if len(opts.SurrogateKeys) > 0 {
		b.WriteString(fmt.Sprintf("  # Tagging for instant purging\n"))
		b.WriteString(fmt.Sprintf("  set beresp.http.Surrogate-Key = \"%s\";\n", strings.Join(opts.SurrogateKeys, " ")))
	}

	if opts.StripCookies {
		b.WriteString("  # Prevent cookie storage on cacheable responses\n")
		b.WriteString("  if (beresp.status == 200 || beresp.status == 301) {\n")
		b.WriteString("    unset beresp.http.Set-Cookie;\n")
		b.WriteString("  }\n")
	}
	b.WriteString("}\n\n")

	b.WriteString("sub vcl_deliver {\n")
	b.WriteString("  # FASTLY deliver\n")
	b.WriteString("  # Never expose internal cache tags to clients\n")
	b.WriteString("  unset resp.http.Surrogate-Key;\n")
	b.WriteString("  unset resp.http.Surrogate-Control;\n")
	b.WriteString("}\n")
	return b.String()
}

func generateCloudflare(opts ConfigOptions) string {
	var b strings.Builder
	b.WriteString("# Cloudflare Cache Rules (Terraform HCL)\n")
	b.WriteString("# Generated by EdgeLens\n\n")
	b.WriteString("resource \"cloudflare_ruleset\" \"edge_cache_rules\" {\n")
	b.WriteString("  zone_id = var.cloudflare_zone_id\n")
	b.WriteString("  name    = \"EdgeLens Dynamic Cache Optimization\"\n")
	b.WriteString("  kind    = \"zone\"\n")
	b.WriteString("  phase   = \"http_request_cache_settings\"\n\n")

	b.WriteString("  rules {\n")
	b.WriteString("    ref         = \"cache_api_rules\"\n")
	b.WriteString(fmt.Sprintf("    description = \"Edge caching for %s\"\n", opts.PathPrefix))
	b.WriteString(fmt.Sprintf("    expression  = \"(http.request.uri.path wildcard \\\"%s*\\\")\"\n", opts.PathPrefix))
	b.WriteString("    action      = \"set_cache_settings\"\n")
	b.WriteString("    action_parameters {\n")
	b.WriteString("      cache = true\n")
	b.WriteString("      edge_ttl {\n")
	b.WriteString("        mode = \"override_origin\"\n")
	b.WriteString(fmt.Sprintf("        default = %d\n", opts.EdgeTTLSeconds))
	b.WriteString("      }\n")
	b.WriteString("      browser_ttl {\n")
	b.WriteString("        mode = \"override_origin\"\n")
	b.WriteString(fmt.Sprintf("        default = %d\n", opts.BrowserTTLSeconds))
	b.WriteString("      }\n")

	if opts.EnableSWR || opts.EnableSIE {
		b.WriteString("      serve_stale {\n")
		if opts.EnableSIE {
			b.WriteString("        disable_stale_while_updating = false\n")
		}
		b.WriteString("      }\n")
	}

	if opts.StripMarketingQP {
		b.WriteString("      query_string {\n")
		b.WriteString("        ignore = true\n")
		b.WriteString("      }\n")
	}

	b.WriteString("    }\n")
	b.WriteString("  }\n")
	b.WriteString("}\n")
	return b.String()
}

func generateCloudFront(opts ConfigOptions) string {
	var b strings.Builder
	b.WriteString("# AWS CloudFront Cache Policy (Terraform HCL)\n")
	b.WriteString("# Generated by EdgeLens\n\n")
	b.WriteString("resource \"aws_cloudfront_cache_policy\" \"edgelens_policy\" {\n")
	b.WriteString("  name        = \"edgelens-cache-policy\"\n")
	b.WriteString("  comment     = \"Generated by EdgeLens RFC 9111 Workbench\"\n")
	b.WriteString(fmt.Sprintf("  default_ttl = %d\n", opts.EdgeTTLSeconds))
	b.WriteString("  max_ttl     = 31536000\n")
	b.WriteString("  min_ttl     = 0\n\n")

	b.WriteString("  parameters_in_cache_key_and_forwarded_to_origin {\n")
	b.WriteString("    cookies_config {\n")
	if opts.StripCookies {
		b.WriteString("      cookie_behavior = \"none\"\n")
	} else {
		b.WriteString("      cookie_behavior = \"all\"\n")
	}
	b.WriteString("    }\n\n")

	b.WriteString("    headers_config {\n")
	b.WriteString("      header_behavior = \"whitelist\"\n")
	b.WriteString("      headers {\n")
	b.WriteString("        items = [\"Accept-Encoding\"]\n")
	b.WriteString("      }\n")
	b.WriteString("    }\n\n")

	b.WriteString("    query_strings_config {\n")
	if opts.StripMarketingQP {
		b.WriteString("      query_string_behavior = \"none\"\n")
	} else {
		b.WriteString("      query_string_behavior = \"all\"\n")
	}
	b.WriteString("    }\n")
	b.WriteString("  }\n")
	b.WriteString("}\n")
	return b.String()
}
